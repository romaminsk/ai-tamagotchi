_VARIANTS = (FALLBACK_PHRASES, EVENT_PHRASES)


def get_fallback(mood: str = "neutral", event: str | None = None,
                 index: int = 0) -> str:
    """Заготовленная фраза по настроению и/или событию, по кругу."""
    phrase = None
    if event and event in EVENT_PHRASES:
        options = EVENT_PHRASES[event]
        phrase = options[index % len(options)]
    if phrase is None:
        options = FALLBACK_PHRASES.get(mood) or FALLBACK_PHRASES["neutral"]
        phrase = options[index % len(options)]
    return phrase
