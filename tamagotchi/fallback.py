_STATE: dict = {}


def _cycle(options: list[str], state: dict) -> str:
    """Случайный обход списка без повторов подряд (state: last, pool)."""
    if len(options) <= 1:
        return options[0] if options else ""
    if not state.get("pool"):
        pool = list(range(len(options)))
        random.shuffle(pool)
        if state.get("last") is not None and pool and pool[0] == state["last"]:
            pool[0], pool[-1] = pool[-1], pool[0]
        state["pool"] = pool
    idx = state["pool"].pop()
    while idx == state.get("last") and state["pool"]:
        state["pool"].insert(0, idx)
        idx = state["pool"].pop()
    state["last"] = idx
    return options[idx]


def get_fallback(mood: str = "neutral", event: str | None = None,
                 index: int = 0) -> str:
    """Заготовленная фраза по настроению/событию, случайно, без повторов подряд.

    index поддержан для совместимости: если передан, шагает по кругу.
    """
    if event and event in EVENT_PHRASES:
        options = EVENT_PHRASES[event]
        key = ("event", event)
    else:
        options = FALLBACK_PHRASES.get(mood) or FALLBACK_PHRASES["neutral"]
        key = ("mood", mood or "neutral")
    if index:
        return options[index % len(options)]
    state = _STATE.setdefault(key, {"last": None, "pool": []})
    return _cycle(options, state)
